def groups(site: str) -> Dict[str, Dict[str, object]]:
    return TOPIC_BANK.get(site, {})


def all_keywords(site: str) -> List[str]:
    return [kw for g in groups(site).values() for kw, _v, _m in g["items"]]  # type: ignore[union-attr]


def group_of(site: str, keyword: str) -> Optional[str]:
    for name, g in groups(site).items():
        if any(kw == keyword for kw, _v, _m in g["items"]):  # type: ignore[union-attr]
            return name
    return None


def wp_category(site: str, keyword: str) -> Optional[str]:
    name = group_of(site, keyword)
    return str(groups(site)[name]["wp"]) if name else None
