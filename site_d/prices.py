    for i in recipe["ingredients"]:
        if not i["g"]:
            continue
        total += i["g"] * PRICE_100G[i["n"]] / 100.0
    per = total / max(1, recipe["servings"])
    return max(100, int(round(per / 100.0)) * 100)
