def must_for(query: str) -> Optional[List[tuple]]:
    return _MUST.get(query)


def name_matches(name: str, groups: Optional[List[tuple]]) -> bool:
    if not groups:
        return True
    lowered = (name or "").lower()
    for group in groups:
        if group and group[0].startswith("!"):  # '!'로 시작하는 묶음은 "이 단어들이 하나도 없어야 한다"
            banned = (group[0][1:],) + tuple(group[1:])
            if any(term.lower() in lowered for term in banned):
                return False
        elif not any(term.lower() in lowered for term in group):
            return False
    return True


def match_topic(keyword: str) -> Optional[Dict[str, object]]:
    text = keyword or ""
    for rule in TOPIC_RULES:
        if any(k in text for k in rule["keys"]):  # type: ignore[union-attr]
            return rule
    return None


def queries_for(keyword: str) -> List[str]:
    rule = match_topic(keyword)
    return list(rule["queries"]) if rule else []  # type: ignore[arg-type]


def all_topic_queries() -> List[str]:
    seen: List[str] = []
    for rule in TOPIC_RULES:
        for q in rule["queries"]:  # type: ignore[union-attr]
            if q not in seen:
                seen.append(q)
    return seen
